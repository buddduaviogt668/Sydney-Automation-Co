def process(fn, dry_run=False):
    with open(fn, "r", encoding="utf-8") as f:
        html = f.read()

    old_head = html[:html.find("<body")] if "<body" in html else html
    body_start = html.find("<body")
    footer_idx = html.find("<footer")

    if dry_run:
        return

    topic = infer_topic(fn)
    tag = make_tag(fn)

    # Generate title from filename
    raw = fn.replace(".html","").replace("blog-","")
    # Remove trailing -sydney for cleaner title
    raw = re.sub(r'-sydney$', '', raw)
    raw = raw.replace("-", " ")
    # Fix casing for known terms before title-casing
    raw = re.sub(r'\bCbus\b', 'C-Bus', raw, flags=re.I)
    raw = re.sub(r'\bDali\b', 'DALI', raw, flags=re.I)
    raw = re.sub(r'\bDynalite\b', 'Dynalite', raw, flags=re.I)
    raw = re.sub(r'\bLed\b', 'LED', raw, flags=re.I)
    raw = re.sub(r'\bPir\b', 'PIR', raw, flags=re.I)
    raw = re.sub(r'\bBms\b', 'BMS', raw, flags=re.I)
    raw = re.sub(r'\bRs232\b', 'RS-232', raw, flags=re.I)
    raw = re.sub(r'\bNabers\b', 'NABERS', raw, flags=re.I)
    raw = re.sub(r'\bEss\b', 'ESS', raw, flags=re.I)
    raw = re.sub(r'\bAfss\b', 'AFSS', raw, flags=re.I)
    # Title-case remaining words, keep part numbers uppercase
    parts = raw.split()
    titled = []
    for p in parts:
        if re.match(r'^L?\d+[a-z0-9]*$', p, re.I):  # part numbers like L5504D2U, 5500PS
            titled.append(p.upper())
        else:
            titled.append(p[0].upper() + p[1:] if len(p) > 0 else p)
    title_fn = " ".join(titled)
    title = f"{title_fn} | Sydney Automation Co."
    desc = title.replace(" | Sydney Automation Co.", "").strip()
    if "Guide" in tag:
        meta_desc = f"{desc}. C-Bus and Dynalite expert guide for Sydney. Practical advice, real symptoms, manufacturer-accredited tips. Call 0422 469 739."
    elif "Fault" in tag or "Repair" in tag:
        meta_desc = f"{desc}. Same-day C-Bus and Dynalite fault diagnosis and repair across Sydney. Accredited Clipsal/Schneider technicians. Call 0422 469 739."
    elif "Energy" in tag:
        meta_desc = f"{desc}. Reduce lighting energy costs by 40-60% with C-Bus and Dynalite automation. Occupancy sensors, daylight harvesting, scheduling. Call 0422 469 739."
    else:
        meta_desc = f"{desc}. C-Bus and Dynalite lighting control by Sydney Automation Co. Accredited specialists. Same-day service. Call 0422 469 739."

    canon = f"https://sydneyautomationco.com.au/{fn.replace('.html', '')}"

    # Determine content type
    f_lower = fn.lower()
    if any(w in f_lower for w in ["energy", "saving", "savings", "efficiency"]):
        is_energy = True
        sections = get_energy_content(topic)
    elif any(w in f_lower for w in ["repair", "fault", "fix", "failure", "stuck", "crash", "problem", "flicker", "overheat", "noise", "offline"]):
        is_energy = False
        sections = get_repair_content(topic)
    else:
        is_energy = False
        sections = get_general_content(topic)

    h1 = title.split("|")[0].strip()
    subtitle = topic.title()
    if is_energy:
        subtitle += " \u2014 Energy savings, automation, and compliance for Sydney"

    new_body = make_body(tag, h1, subtitle, topic, sections)

    # ─── FIX HEAD SECTION ───
    # Title
    html = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", html)

    # Meta description (handle both name="description" content="..." AND content="..." name="description")
    meta_desc_escaped = meta_desc.replace("&", "&amp;")
    html = re.sub(
        r'<meta\s+(?:name="description"\s+content="[^"]*"|content="[^"]*"\s+name="description")',
        f'<meta name="description" content="{meta_desc_escaped}"',
        html
    )

    # Canonical
    html = re.sub(r'<link rel="canonical" href="[^"]*"', f'<link rel="canonical" href="{canon}"', html)

    # OG url
    html = re.sub(r'<meta content="https://sydneyautomationco\.com\.au/[^"]*" property="og:url"', f'<meta content="{canon}" property="og:url"', html)

    # OG title
    og_t = title.replace("&", "&amp;")
    html = re.sub(r'<meta content="[^"]*" property="og:title"', f'<meta content="{og_t}" property="og:title"', html)

    # OG description (handle both formats)
    og_d = meta_desc[:200].replace("&", "&amp;")
    html = re.sub(
        r'<meta\s+(?:content="[^"]*"\s+property="og:description"|property="og:description"\s+content="[^"]*")',
        f'<meta content="{og_d}" property="og:description"',
        html
    )

    # Twitter title/desc
    html = re.sub(
        r'<meta\s+(?:content="[^"]*"\s+name="twitter:title"|name="twitter:title"\s+content="[^"]*")',
        f'<meta content="{og_t}" name="twitter:title"',
        html
    )
    html = re.sub(
        r'<meta\s+(?:content="[^"]*"\s+name="twitter:description"|name="twitter:description"\s+content="[^"]*")',
        f'<meta content="{og_d}" name="twitter:description"',
        html
    )

    # ─── REPLACE BODY ───
    body_end = html.rfind("</body>")
    if body_end < 0:
        html += f"\n<body>\n\n{new_body}\n\n</body>\n</html>"
    else:
        # Strip any existing <body> tags and their content before </body>
        head_end = 0
        hd = html.rfind("</head>", 0, body_end)
        if hd >= 0:
            head_end = hd + 7
        else:
            fb = html.find("<body", 0, body_end)
            limit = fb if fb >= 0 else body_end
            # Prefer </style> (always in head) over </script> (may be in body)
            st = html.rfind("</style>", 0, limit)
            if st >= 0:
                head_end = st + 7
            sc = html.rfind("</script>", 0, limit)
            if sc >= 0 and st < 0:
                head_end = sc + 9
            if fb >= 0 and head_end == 0:
                head_end = fb
        prefix = html[:head_end]
        suffix = html[body_end:]
        html = prefix + "\n\n<body>\n\n" + new_body + "\n\n" + suffix

    with open(fn, "w", encoding="utf-8") as f:
        f.write(html)

    sz = len(html)
    return sz

